/**
 * Backoffice icon codegen (DESIGN_AUDIT §2.12.2 "Backoffice" + UI glyphs). Reads the framework-neutral
 * Material Symbols Rounded data emitted by `@da/ui` (`packages/ui/icons.data.json`) and writes
 * `src/generated/icons.ts` with only the glyphs the backoffice renders, so the client bundle never
 * carries the whole icon set. Run with `node scripts/gen-icons.ts` (`pnpm --filter @da/backoffice
 * generate`); `--check` exits 1 when the committed file is stale.
 */
import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const HERE = dirname(fileURLToPath(import.meta.url));
const APP = join(HERE, '..');
const SOURCE = join(APP, '..', '..', 'packages', 'ui', 'icons.data.json');
const TARGET = join(APP, 'src', 'generated', 'icons.ts');

/** Every glyph the backoffice uses, sorted. Navigation icons follow DESIGN_AUDIT §2.12.2. */
