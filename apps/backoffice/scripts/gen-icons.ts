interface IconData {
  source: string;
  viewBox: string;
  regular: string;
  fill?: string;
}

export function render(data: { version: string; icons: Record<string, IconData> }): string {
  const missing = BACKOFFICE_ICONS.filter((name) => data.icons[name] === undefined);
  if (missing.length > 0) {
    throw new Error(`Icons missing from packages/ui/icons.data.json: ${missing.join(', ')}`);
  }
  const entries = BACKOFFICE_ICONS.map((name) => {
    const icon = data.icons[name];
    if (icon === undefined) throw new Error(`Icon missing: ${name}`);
    const fill = icon.fill === undefined ? '' : `, fill: ${JSON.stringify(icon.fill)}`;
    return `  ${name}: { viewBox: ${JSON.stringify(icon.viewBox)}, regular: ${JSON.stringify(icon.regular)}${fill} },`;
  });
  return [
    `// Generated by apps/backoffice/scripts/gen-icons.ts from @material-symbols/svg-400@${data.version} (rounded) via packages/ui/icons.data.json. Do not edit.`,
    '',
    'export interface IconGlyph {',
    '  readonly viewBox: string;',
    '  readonly regular: string;',
    '  readonly fill?: string;',
    '}',
    '',
    'export const ICONS = {',
    ...entries,
    '} as const satisfies Record<string, IconGlyph>;',
    '',
    'export type IconName = keyof typeof ICONS;',
    '',
  ].join('\n');
}

function main(): void {
  const data = JSON.parse(readFileSync(SOURCE, 'utf8')) as {
    version: string;
    icons: Record<string, IconData>;
  };
  const output = render(data);
  if (process.argv.includes('--check')) {
    const current = existsSync(TARGET) ? readFileSync(TARGET, 'utf8') : '';
    if (current !== output) {
      console.error(
        'src/generated/icons.ts is stale: run `pnpm --filter @da/backoffice generate`.',
      );
      process.exit(1);
    }
    return;
  }
  mkdirSync(dirname(TARGET), { recursive: true });
  writeFileSync(TARGET, output);
  console.info(`icons: wrote ${String(BACKOFFICE_ICONS.length)} glyphs to src/generated/icons.ts`);
}

if (process.argv[1] === fileURLToPath(import.meta.url)) main();
