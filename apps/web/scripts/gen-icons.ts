/**
 * DOM icon generation for apps/web. Reads the framework-neutral Material Symbols Rounded path data
 * that `@da/ui` emits (`packages/ui/icons.data.json`, T-1.03) and writes one small React component
 * per icon the website uses to `src/components/icons/generated/`:
 *   - `fill="currentColor"`, so every icon takes its colour from the text colour (tokens only);
 *   - `aria-hidden` by default; passing `label` makes it `role="img"` with that accessible name;
 *   - `filled` switches to the FILL 1 path (active / AI-marker style).
 * Output is deterministic (sorted, no timestamps); `test/icons.test.ts` fails on drift.
 *
 * Usage: node scripts/gen-icons.ts [--check]
 */
import { mkdirSync, readFileSync, readdirSync, rmSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const APP_DIR = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const DATA_FILE = resolve(APP_DIR, '..', '..', 'packages', 'ui', 'icons.data.json');
const OUT_DIR = join(APP_DIR, 'src', 'components', 'icons', 'generated');

/** Every Material Symbol the website renders. Adding a name here and re-running is enough. */
